import { db, setMeta, useDatabase } from '../db'
import { setCurrentUserId } from '../sharing'
import { AGENT_EXCLUSIONS_KEY } from '../agentAccess'
import type { ProposedChange } from '../assistantTypes'
import vectors from './plan.vectors.json'
import { manifest } from './manifest'
import { ArgError, ToolError } from './args'
import { loadSnapshot } from './data'
import { IMPLEMENTED } from './loop'
